// Renders the check catalog (docs/checks.md) from check metadata.

import { DEFAULT_NAMING, DEFAULT_THRESHOLDS } from "../config.js";
import { CHECKS } from "./index.js";

const TYPE_NAMES = {
  gate: "gates",
  dynamicConfig: "dynamic configs",
  experiment: "experiments",
  segment: "segments",
  metric: "metrics",
  layer: "layers",
  holdout: "holdouts",
  project: "project settings",
  tag: "tags",
};

const READS = {
  gates: "gates",
  dynamicConfigs: "dynamic configs",
  experiments: "experiments",
  segments: "segments",
  metrics: "metrics",
  layers: "layers",
  holdouts: "holdouts",
  tags: "tags",
  auditLogs: "audit log",
  users: "project members (--users)",
  reviewSettings: "review settings",
};

const join = (xs) => (xs.length <= 1 ? xs.join("") : `${xs.slice(0, -1).join(", ")} and ${xs[xs.length - 1]}`);

function settingText(key) {
  if (key.startsWith("naming.")) {
    const name = key.slice("naming.".length);
    return `\`${key}\` (default \`${DEFAULT_NAMING[name]}\`)`;
  }
  return `\`thresholds.${key}\` (default ${DEFAULT_THRESHOLDS[key]})`;
}

export function renderCatalog() {
  const lines = [
    "# Check catalog",
    "",
    "<!-- Generated by `npm run docs` from the metadata in src/checks. Edit the check modules, not this file. -->",
    "",
    `statsig-audit runs ${CHECKS.length} checks. Each one is a pure function over the snapshot, so the same snapshot always gives the same findings.`,
    "",
    "Ids are stable and never reused. The letter is the area: **G** gates, **D** dynamic configs, **E** experiments, **X** checks across entity types, **A** audit log and settings, **N** naming. Numbers have gaps on purpose: they leave room for checks that were considered and not shipped in this version.",
    "",
    "Severity says when to act. **High**: now, because it changes what users get today or hides that it does. **Medium**: this quarter. **Low**: hygiene. A few checks set the severity per finding, as noted below.",
    "",
    "Archived entities are never reported. Statsig's built-in metrics (type `user`) are skipped wherever descriptions or verification are checked.",
    "",
    "| Id | Check | Severity | Applies to |",
    "| --- | --- | --- | --- |",
  ];
  for (const c of CHECKS) {
    const anchor = `${c.id} ${c.title}`.toLowerCase().replace(/[^a-z0-9 -]/g, "").replace(/ /g, "-");
    lines.push(`| [${c.id}](#${anchor}) | ${c.title} | ${c.severity} | ${join(c.appliesTo.map((t) => TYPE_NAMES[t] || t))} |`);
  }
  lines.push("");
  for (const c of CHECKS) {
    lines.push(`## ${c.id} ${c.title}`, "");
    lines.push(`**Severity:** ${c.severity}. **Reads:** ${join(c.requires.map((r) => READS[r] || r))}.`, "");
    lines.push(`**What it finds.** ${c.what}`, "");
    lines.push(`**Why it matters.** ${c.rationale}`, "");
    lines.push(`**How to fix.** ${c.action}`, "");
    lines.push(`**Overlap with Statsig.** ${c.overlap}`, "");
    if (c.deep) lines.push(`**With --deep.** ${c.deep}`, "");
    if (c.settings?.length) lines.push(`**Settings.** ${join(c.settings.map(settingText))}.`, "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}
